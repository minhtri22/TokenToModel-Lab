    ck('36_no_memory_is_empty',all(c['none_memory']==[] for c in cases))
    ck('37_hard_negative_count_four',all(sum(sum(x!=y for x,y in zip(retriever.parsed_attributes(v['retrieval_text']),retriever.parsed_attributes(next(x['retrieval_text'] for x in c['correct_memory'] if x['key']==c['target_key']))))==1 for v in c['correct_memory'] if v['key']!=c['target_key'])==4 for c in cases))
    ck('38_schema_answer_token_flag',all(c['answer_only_scoring'] for c in cases))
    ck('39_build_deterministic_digest',hashlib.sha256(fixture.serialized(fixture.build())).hexdigest()==EXPECTED_PROBE_SHA)
    # Separate synthetic fixtures: NO retrieval calls on the actual 192 cases.
    bank=custom_bank()
