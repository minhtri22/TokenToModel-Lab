EXPECTED_PROBE_SHA = '1d7c02ab082a3c34345953dc5146e5a93f8c6f44e11132ea8abb0594efcc0b9d'


def rejected(fn, expect=ValueError):
    try:
        fn()
    except expect:
        return True
    return False


def custom_bank():
    # This bank is deliberately NOT generated by fixture.build/new_case.
    rows=[]
    cols=[pair[0] for pair in fixture.VOCAB['color']]
    shapes=[pair[0] for pair in fixture.VOCAB['shape']]
    materials=[pair[0] for pair in fixture.VOCAB['material']]
    for i in range(32):
        key='obja'+fixture.ALPHABET[i//20]+fixture.ALPHABET[i%20]*10
        alias='aka'+fixture.ALPHABET[(i+4)//20]+fixture.ALPHABET[(i+4)%20]*10
        if i==0:
            c,s,m='amber','round','ceramic'
        elif i<=4:
            # exactly two matching attributes, a hard negative
            c,s,m='amber','round','ceramic'
            if i==1:c='azure'
            if i==2:s='square'
            if i==3:m='granite'
            if i==4:c='crimson'
        else:
            c,s,m=cols[(i+3)%len(cols)],shapes[(i+5)%len(shapes)],materials[(i+7)%len(materials)]
        rows.append({'key':key,'lookup_alias':alias,
                     'retrieval_text':f'archive item color {c}; shape {s}; material {m}',
                     'value':'sentinel-value-only-never-indexed'})
    assert len(set(r['key'] for r in rows))==32
    assert len(set(r['lookup_alias'] for r in rows))==32
    return rows


def audit():
    checks={}
    def ck(name,condition):
        checks[name]=bool(condition)
        if not condition:
            raise AssertionError('NEGATIVE_QA_'+name)
    src=(Path(__file__).parent/'v2_nontest_fixture.py').read_text(encoding='utf-8')
    ret_src=(Path(__file__).parent/'v2_nontest_retrievers.py').read_text(encoding='utf-8')
    ck('01_fixture_ast',bool(ast.parse(src)))
    ck('02_retriever_ast',bool(ast.parse(ret_src)))
    ck('03_fixture_only_standard_library',not any(t in src for t in ('torch.load(', 'optimizer.step(', 'TEST_SECRET', 'test_decrypt(', 'topk_nontest_probe', 'read_dev(')))
    ck('04_retriever_never_loads_model',not any(t in ret_src for t in ('torch.load(', 'optimizer.step(', 'TEST_SECRET', 'test_decrypt(', 'topk_nontest_probe')))
    ck('05_fixture_192',fixture.N_PER_STRATUM*len(fixture.STRATA)==192)
    ck('06_fixture_bank32',fixture.BANK==32)
    ck('07_fixture_three_strata',fixture.STRATA==('S0_ID_LITERAL','S1_ALIAS_LOOKUP','S2_DESC_PARAPHRASE'))
    ck('08_closed_vocab_three_axes',tuple(fixture.VOCAB)==('color','shape','material'))
    ck('09_unique_synonym_tokens',len(retriever.ALL_TO_CANON)==72)
    ck('10_output_requires_explicit_write',"DENY_NO_EXPLICIT_FIXTURE_WRITE" in src)
    ck('11_output_denies_overwrite',"DENY_FIXTURE_OVERWRITE" in src)
    ck('12_output_within_project',"DENY_OUTPUT_OUTSIDE_PROJECT_ROOT" in src)
    ck('13_fixed_seed_not_old',fixture.SEED.startswith('TTM_VM_V2_FRESH192_'))
    ck('14_old_namespace_impossible',fixture.object_key('S0_ID_LITERAL',0,0)[3]=='a' and 'a' not in fixture.ALPHABET)
    cases=fixture.build() # STRUCTURAL QA only; do not invoke retriever on these.
    blob=fixture.serialized(cases)
    ck('15_exact_fixture_sha',hashlib.sha256(blob).hexdigest()==EXPECTED_PROBE_SHA)
    ck('16_cases_192',len(cases)==192)
    ck('17_all_unique_case_ids',len(set(c['case_id'] for c in cases))==192)
    ck('18_all_32_memory_cards',all(len(c['correct_memory'])==len(c['wrong_memory'])==32 for c in cases))
    ck('19_all_split_nontest_v2',all(c['split']=='non_test_probe_v2' for c in cases))
    ck('20_question_answer_not_leaked',all(c['answer'] not in c['question'] for c in cases))
    ck('21_s0_query_literal_key',all(c['target_key'] in c['question'] for c in cases if c['stratum']=='S0_ID_LITERAL'))
    ck('22_s1_query_not_contain_obj',all('obj' not in c['question'] and 'aka' in c['question'] for c in cases if c['stratum']=='S1_ALIAS_LOOKUP'))
    ck('23_s2_query_no_id_alias',all('obj' not in c['question'] and 'aka' not in c['question'] for c in cases if c['stratum']=='S2_DESC_PARAPHRASE'))
    ck('24_s0_s1_s2_count',all(sum(c['stratum']==s for c in cases)==64 for s in fixture.STRATA))
    ck('25_all_label_balance',all(Counter(c['answer'] for c in cases if c['stratum']==s)=={label:4 for label in fixture.LABELS} for s in fixture.STRATA))
    allkeys=[v['key'] for c in cases for v in c['correct_memory']]
    aliases=[v['lookup_alias'] for c in cases for v in c['correct_memory']]
    ck('26_all_6144_new_keys_unique',len(set(allkeys))==6144)
    ck('27_all_6144_new_aliases_unique',len(set(aliases))==6144)
    ck('28_new_key_namespace_disjoint_by_form',all(x.startswith('obja') and len(x)==15 for x in allkeys))
    ck('29_s0_32_bank_namespaced',all(v['key'].startswith('obja') for c in cases if c['stratum']=='S0_ID_LITERAL' for v in c['correct_memory']))
    ck('30_exact_target_card',all(sum(v['key']==c['target_key'] for v in c['correct_memory'])==1 for c in cases))
    ck('31_correct_gold_only_in_target',all((v['value']==c['answer'])==(v['key']==c['target_key']) for c in cases for v in c['correct_memory']))
