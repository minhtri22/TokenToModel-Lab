def rejects(fn, types=(ValueError,TypeError,FileExistsError)):
    try:fn()
    except types:return True
    return False


def mock_bank():
    """Completely separate fixture, not generated by fixture.build/new_case."""
    out=[]
    for j in range(32):
        key='obju' + fixture.ALPHABET[j//20] + fixture.ALPHABET[j%20]*10
        attrs=('amber','round','ceramic') if j==0 else (
            fixture.VOCAB['color'][(j+1)%12],
            fixture.VOCAB['shape'][(j+3)%12],
            fixture.VOCAB['material'][(j+5)%12])
        if j>0 and attrs==('amber','round','ceramic'):
            attrs=('azure','square','cotton')
        out.append({'key':key,'source_id':'src-north' if j==0 else 'src-east',
                    'retrieval_text':fixture.encode_description(attrs)})
    return out


def truth_candidates(case):
    """Rule-only independent truth test using structured metadata, not ranker."""
    cons=case['truth_constraints']
    if cons['invalid']:
        return []
    match=[]
    for r in case['public_index']:
        parts=r['retrieval_text'].split('; ')
        attrs={part.split(' ',1)[0]:part.split(' ',1)[1] for part in parts}
        if cons['source'] is not None and r['source_id']!=cons['source']:
            continue
        if any(attrs.get(a)!=v for a,v in cons['positive'].items()):continue
        if any(attrs.get(a)==v for a,v in cons['negative'].items()):continue
        match.append(r['key'])
    return match


def audit():
    checks={}
    def ck(name,okay):
        checks[name]=bool(okay)
        if not okay:raise AssertionError('V3_NEGATIVE_QA_'+name)
    files=['v3_fresh256_fixture.py','v3_nonoracle_retriever.py','v3_p1_reviewer_custody.py']
    source=[(Path(__file__).parent/name).read_text('utf8') for name in files]
    for i,s in enumerate(source,1):ck(f'AST_{i}',bool(ast.parse(s)))
    ck('NO_TRAIN_OR_MODEL_LOAD_IN_FIXTURE',not any(x in source[0] for x in ('torch.load(','.backward(', 'optimizer.step(', 'TEST_SECRET','DEV_AGGREGATE','PER_STORY_QA_PRIVATE')))
    ck('NO_MODEL_LOAD_IN_RETRIEVER',not any(x in source[1] for x in ('torch.load(','.backward(', 'optimizer.step(', 'TEST_SECRET')))
    ck('NO_TRAIN_IN_REVIEWER',not any(x in source[2] for x in ('torch.load(','.backward(', 'optimizer.step(', 'TEST_SECRET')))
    ck('PRIVATE_FIXTURE_WRITE_REQUIRES_OPTIN','DENY_WRITE_WITHOUT_EXPLICIT_OPTIN' in source[0])
    ck('PRIVATE_FIXTURE_OVERWRITE_DENIED','DENY_OVERWRITE_FROZEN_FIXTURE' in source[0])
    ck('OWNER_PROJECT_SCOPE_ENFORCED','DENY_OUTSIDE_PROJECT_ROOT' in source[0])
    ck('V3_NEW_SEED_LOCKED',fixture.SEED.startswith('TTM_VM_V3_FRESH256_'))
    ck('V3_NAMESPACE_DISJOINT_V2','u' not in fixture.ALPHABET and fixture.objkey('P0_KNOWN_WIRING',0,0).startswith('obju'))
    ck('EIGHT_EXACT_STRATA',len(fixture.STRATA)==8 and len(set(fixture.STRATA))==8)
    ck('NEW_P1_SURFACE_PRESENT',len(fixture.PROPOSED_P1)==3 and all(len(x)==6 for x in fixture.PROPOSED_P1.values()))
    all_old=set(V2_OLD_SURFACE)|{word for rows in fixture.VOCAB.values() for word in rows}
    ck('NOVEL_PHRASES_NOT_IDENTICAL_TO_V2',all(term not in all_old for rows in fixture.PROPOSED_P1.values() for term in rows))
    ck('NOVEL_PHRASES_NO_V2_LEXEME_BOUNDARY',all(not any(re.search(r'(?<![a-z0-9])'+re.escape(old)+r'(?![a-z0-9])',term) for old in all_old) for rows in fixture.PROPOSED_P1.values() for term in rows))
    data=fixture.build()  # S C H E M A   O N L Y, no Retriever calls on data
    b=fixture.serialized(data)
    ck('EXACT_DATA_BYTE_SHA',hashlib.sha256(b).hexdigest()==EXPECTED_FIXTURE_SHA)
    ck('EXACT_DATA_BYTE_SIZE',len(b)==EXPECTED_FIXTURE_BYTES)
    ck('TOTAL_CASES_256',len(data)==256)
    ck('EACH_STRATUM_32',Counter(c['stratum'] for c in data)=={s:32 for s in fixture.STRATA})
    ck('ALL_CASE_IDS_UNIQUE',len({c['case_id'] for c in data})==256)
    ck('ALL_SPLITS_FRESH_NONTEST',all(c['split']=='non_test_probe_v3' for c in data))
    ck('ALL_PUBLIC_BANKS32',all(len(c['public_index'])==32 for c in data))
    ck('ALL_PUBLIC_BANKS_ONLY_PUBLIC_FIELDS',all(all(set(x)==retriever.ALLOWED for x in c['public_index']) for c in data))
    ck('NO_ANSWER_IN_PUBLIC_QUERY',all(c['answer'] is None or c['answer'] not in c['question'] for c in data))
    ck('NEGATIVE_NO_GOLD_KEY_ANSWER',all(c['target_key'] is None and c['answer'] is None for c in data if c['gold_action']=='ABSTAIN'))
    ck('NEGATIVE_NO_CORRECT_WRONG_MEMORY',all(c['correct_memory'] is None and c['wrong_memory'] is None for c in data if c['gold_action']=='ABSTAIN'))
    ck('POSITIVE_GOLD_PRESENT',all(c['target_key'] and c['answer'] and c['correct_memory'] and c['wrong_memory'] for c in data if c['gold_action']=='SELECT'))
    ck('POSITIVE_128',sum(c['gold_action']=='SELECT' for c in data)==128)
    ck('NEGATIVE_128',sum(c['gold_action']=='ABSTAIN' for c in data)==128)
    ck('POSITIVE_96_PRIMARY',sum(c['gold_action']=='SELECT' and c['stratum']!='P0_KNOWN_WIRING' for c in data)==96)
    ck('NEGATIVE_PUBLIC_INDEX_NEVER_VALUE',all('value' not in card for c in data for card in c['public_index']))
    keys=[x['key'] for c in data for x in c['public_index']]
    ck('GLOBAL_KEY_UNIQUE_8192',len(keys)==8192 and len(set(keys))==8192)
    ck('NAMESPACE_OBJu',all(k.startswith('obju') and len(k)==15 for k in keys))
    ck('PUBLIC_SOURCE_VALID',all(r['source_id'] in fixture.SOURCES for c in data for r in c['public_index']))
    ck('POSITIVE_TARGET_KEY_ONCE',all(sum(x['key']==c['target_key'] for x in c['public_index'])==1 for c in data if c['gold_action']=='SELECT'))
    ck('POSITIVE_CORRECT_WRONG_ORDER_SAME',all([x['key'] for x in c['correct_memory']]==[x['key'] for x in c['wrong_memory']] for c in data if c['gold_action']=='SELECT'))
    ck('POSITIVE_ONLY_ONE_VALUE_SWAPPED',all(sum(x['value']!=y['value'] for x,y in zip(c['correct_memory'],c['wrong_memory']))==1 for c in data if c['gold_action']=='SELECT'))
    ck('POSITIVE_TARGET_VALUE_CORRECT',all(next(x['value'] for x in c['correct_memory'] if x['key']==c['target_key'])==c['answer'] for c in data if c['gold_action']=='SELECT'))
    ck('POSITIVE_WRONG_REMOVES_GOLD',all(next(x['value'] for x in c['wrong_memory'] if x['key']==c['target_key'])!=c['answer'] for c in data if c['gold_action']=='SELECT'))
    ck('POSITIVE_LABELS_BALANCED',all(Counter(c['answer'] for c in data if c['stratum']==s)=={v:2 for v in fixture.LABELS} for s in fixture.STRATA[:4]))
    ck('P1_ALL_PENDING_HUMAN_REVIEW',all(c['review_status']=='PENDING_TWO_INDEPENDENT_HUMAN_REVIEWS' for c in data if c['stratum']=='P1_UNSEEN_PARAPHRASE'))
    ck('P1_32_BLIND_PUBLIC_VIEWS',len([custody.public_view(c) for c in data if c['stratum']=='P1_UNSEEN_PARAPHRASE'])==32)
    ck('P1_VIEW_NO_GOLD_FIELDS',all(not (set(custody.public_view(c)) & {'answer','target_key','gold_action','truth_constraints','stratum','correct_memory','wrong_memory'}) for c in data if c['stratum']=='P1_UNSEEN_PARAPHRASE'))
    ck('P1_NEW_SURFACE_IN_QUERY',all(any(novel in c['question'] for term in fixture.PROPOSED_P1.values() for novel in term) for c in data if c['stratum']=='P1_UNSEEN_PARAPHRASE'))
    for s in fixture.STRATA:
        cases=[c for c in data if c['stratum']==s]
        matches=[truth_candidates(c) for c in cases]
        if s.startswith('P'):
            ck('TRUTH_'+s+'_EXACT_UNIQUE',all(v==[c['target_key']] for c,v in zip(cases,matches)))
        elif s in ('N0_UNDERSPECIFIED','N1_DUPLICATE_MATCH'):
            ck('TRUTH_'+s+'_MULTIMATCH',all(len(v)>=2 for v in matches))
        else:
            ck('TRUTH_'+s+'_ZERO_MATCH',all(len(v)==0 for v in matches))
    ck('P2_REAL_DUPLICATE_DIFFERENT_SOURCE',all(sum(x['retrieval_text']==next(r['retrieval_text'] for r in c['public_index'] if r['key']==c['target_key']) for x in c['public_index'])>=2 for c in data if c['stratum']=='P2_PROVENANCE_UNIQUE'))
    ck('N1_DUPLICATE_FULL_AND_SOURCE',all(len(truth_candidates(c))>=2 and c['truth_constraints']['source'] for c in data if c['stratum']=='N1_DUPLICATE_MATCH'))
    ck('P3_POSITIVE_NEGATION_PARSER_CONTRACT',all('excluding material ' in c['question'] for c in data if c['stratum']=='P3_NEGATION_UNIQUE'))
    ck('N2_CONTRADICTS_POSITIVE_COLOR',all(c['truth_constraints']['positive']['color']==c['truth_constraints']['negative']['color'] for c in data if c['stratum']=='N2_CONTRADICTORY_QUERY'))
    ck('N3_HALF_OOV_HALF_EXCLUSION',sum('made of xylotherm' in c['question'] for c in data if c['stratum']=='N3_UNRESOLVABLE_OOV_OR_EXCLUSION')==16)
    ck('FIXTURE_BUILD_DETERMINISTIC',hashlib.sha256(fixture.serialized(fixture.build())).hexdigest()==EXPECTED_FIXTURE_SHA)
    # NEGATIVE/DYNAMIC RETRIEVER QA ON A SEPARATE MOCK BANK, NEVER THE 256.
    bank=mock_bank()
    def query(c='amber',s='round',m='ceramic',suffix=''):
        return f'Which tag belongs to the {c} {s} {m} archive item{suffix}? Answer:'
    res=retriever.retrieve(query(),bank)
    ck('MOCK_UNIQUE_SELECT',res.status=='SELECT' and res.indices==(0,))
    ck('MOCK_SELECT_MASK_ONE',sum(retriever.mask(res))==1)
    ck('MOCK_ORDER_INVARIANCE',list(reversed(bank))[retriever.retrieve(query(),list(reversed(bank))).indices[0]]['key']==bank[0]['key'])
    ck('MOCK_P1_NEW_LEXICON_SELECT',retriever.retrieve(query('honey-hued','disklike','fired-earth'),bank).indices==(0,))
    ck('MOCK_SOURCE_ONLY_SELECT',retriever.retrieve(query(suffix=' from source src-north'),bank).indices==(0,))
    provenance=deepcopy(bank);provenance[1]['retrieval_text']=bank[0]['retrieval_text'];provenance[1]['source_id']='src-south'
    ck('MOCK_DUP_DESC_DIFFERENT_SOURCE_AMBIGUOUS_WITHOUT_SOURCE',retriever.retrieve(query(),provenance).status=='ABSTAIN')
    ck('MOCK_PROVENANCE_RESOLVES_DUPLICATE',retriever.retrieve(query(suffix=' from source src-north'),provenance).indices==(0,))
    ck('MOCK_PROVENANCE_OTHER_SOURCE_SELECTS_SECOND',retriever.retrieve(query(suffix=' from source src-south'),provenance).indices==(1,))
    ck('MOCK_UNKNOWN_SOURCE_ABSTAIN',retriever.retrieve(query(suffix=' from source src-unknown'),bank).status=='ABSTAIN')
    duplicate=deepcopy(bank);duplicate[1]['retrieval_text']=bank[0]['retrieval_text'];duplicate[1]['source_id']='src-north'
    ck('MOCK_FULL_DUPLICATE_ABSTAINS',retriever.retrieve(query(suffix=' from source src-north'),duplicate).status=='ABSTAIN')
    ck('MOCK_FULL_DUPLICATE_MASK_ZERO',sum(retriever.mask(retriever.retrieve(query(),duplicate)))==0)
    partial=deepcopy(bank);partial[1]['retrieval_text']=fixture.encode_description(('amber','round','granite'))
    ck('MOCK_UNDERSPECIFIED_ABSTAINS',retriever.retrieve('Which tag belongs to the amber round archive item? Answer:',partial).status=='ABSTAIN')
    ck('MOCK_NEGATION_UNIQUE_SELECT',retriever.retrieve('Which tag belongs to the amber round archive item excluding material granite? Answer:',partial).indices==(0,))
    ck('MOCK_NEGATION_CONTRADICTION_ABSTAINS',retriever.retrieve(query(suffix=' excluding color amber'),bank).status=='ABSTAIN')
    ck('MOCK_NEGATION_EXCLUDES_ALL',retriever.retrieve(query(suffix=' excluding material ceramic'),bank).status=='ABSTAIN')
    ck('MOCK_OOV_ABSTAINS',retriever.retrieve('Which tag belongs to the amber round item made of xylotherm? Answer:',bank).status=='ABSTAIN')
    ck('MOCK_ZERO_MATCH_ABSTAINS',retriever.retrieve(query('amber','round','slate'),bank).status=='ABSTAIN')
    ck('MOCK_ZERO_MASK',sum(retriever.mask(retriever.retrieve(query('amber','round','slate'),bank)))==0)
    ck('MOCK_SOURCE_CONFLICT_AMBIGUOUS_SAFETY',retriever.retrieve(query(suffix=' from source src-north from source src-south'),bank).status=='ABSTAIN')
    ck('MOCK_INVALID_NEGATION_GRAMMAR_ABSTAIN',retriever.retrieve(query(suffix=' excluding unicorn xylotherm'),bank).status=='ABSTAIN')
    ck('MOCK_UNKNOWN_NEGATED_TERM_ABSTAIN',retriever.retrieve(query(suffix=' excluding material xylotherm'),bank).status=='ABSTAIN')
    ck('MOCK_POSITIVE_CONFLICT_ABSTAIN',retriever.retrieve(query('amber azure','round','ceramic'),bank).status=='ABSTAIN')
    ck('MOCK_VALUE_FIELD_REJECTED',rejects(lambda:retriever.retrieve(query(),[dict(x,value='GOLD') for x in bank])))
    ck('MOCK_GOLD_FIELD_REJECTED',rejects(lambda:retriever.retrieve(query(),[dict(x,target_key='GOLD') for x in bank])))
    ck('MOCK_OUTCOME_FIELD_REJECTED',rejects(lambda:retriever.retrieve(query(),[dict(x,gold_action='SELECT') for x in bank])))
    ck('MOCK_CASE_ID_FIELD_REJECTED',rejects(lambda:retriever.retrieve(query(),[dict(x,case_id='P1') for x in bank])))
    ck('MOCK_DUP_KEY_REJECTED',rejects(lambda:retriever.retrieve(query(),[bank[0]]*32)))
    ck('MOCK_WRONG_BANK_LENGTH_REJECTED',rejects(lambda:retriever.retrieve(query(),bank[:31])))
    ck('MOCK_BAD_SOURCE_INDEX_REJECTED',rejects(lambda:retriever.retrieve(query(),[dict(x,source_id='src-bogus') for x in bank])))
    ck('MOCK_EXTRA_FIELD_VALUES_BLIND_FAIL_CLOSED',rejects(lambda:retriever.retrieve(query(),[dict(x,answer='bivor') for x in bank])))
    ck('MOCK_INVALID_RESULT_MASK_REJECTED',rejects(lambda:retriever.mask(retriever.Decision('SELECT',(0,1),'ATTACK'))))
    ck('MOCK_ILLEGAL_ABSTAIN_MASK_REJECTED',rejects(lambda:retriever.mask(retriever.Decision('ABSTAIN',(0,),'ATTACK'))))
    ck('MOCK_NONINT_INDEX_MASK_REJECTED',rejects(lambda:retriever.mask(retriever.Decision('SELECT',(True,),'ATTACK'))))
    ck('RETRIEVER_SIGNATURE_NO_GOLD',list(inspect.signature(retriever.retrieve).parameters)==['question','public_index'])
    # Reviewer custody: reject unsigned and collusive submissions.
    p1=[c for c in data if c['stratum']=='P1_UNSEEN_PARAPHRASE']
    A=custody.review_packet(EXPECTED_FIXTURE_SHA,p1,'A')
    B=custody.review_packet(EXPECTED_FIXTURE_SHA,p1,'B')
    ck('REVIEW_TEMPLATES_32_EACH',len(A['cases'])==len(B['cases'])==32)
    ck('REVIEW_TEMPLATES_UNATTESTED',not A['attest_independent_semantic_mapping'] and not B['attest_independent_semantic_mapping'])
    ck('REVIEWER_CANNOT_APPROVE_UNATTESTED',rejects(lambda:custody.validate_receipts(data,EXPECTED_FIXTURE_SHA,A,B)))
    ck('REVIEWER_SLOTS_DISTINCT',A['slot']=='A' and B['slot']=='B')
    ck('REVIEW_NO_TARGET_OR_ANSWER',all(not (set(c) & {'answer','target_key','gold_action','truth_constraints'}) for c in A['cases']))
    ck('REVIEW_FIXTURE_SHA_BOUND',A['fixture_sha256']==B['fixture_sha256']==EXPECTED_FIXTURE_SHA)
    ck('NO_REVIEW_RECEIPTS_IN_SOURCE_QA',True)
    return checks,hashlib.sha256(b).hexdigest(),len(b)


def main():
    a=argparse.ArgumentParser()
    a.add_argument('--out',type=Path,required=True)
    args=a.parse_args()
    if args.out.exists():raise FileExistsError('QA_REFUSE_OVERWRITE')
    checks,sha,n=audit()
    report={'schema':'ttm.vm.v3.independent_fixture_truth_and_nonoracle_negative_qa.v1',
            'status':'PASS_SOURCE_STRUCTURAL_AND_MOCK_RETRIEVER_QA',
            'qa_passed':len(checks),'qa_total':len(checks),'checks':checks,
            'private_fixture_sha256':sha,'private_fixture_bytes':n,'cases':256,
            'actual_v3_probe_retrieval_calls':0,'Reader_forward_calls':0,
            'optimizer_steps':0,'old_probe_scored':False,'dev_scored':False,
            'test_opened':False,'gpu_used':False,
            'P1_independent_human_raters':'PENDING_NOT_SUBSTITUTED_BY_MOCK_QA',
            'scientific_release':'HOLD'}
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(report,indent=2,sort_keys=True)+'\n',encoding='utf8')
    print(json.dumps({'status':report['status'],'checks':f'{len(checks)}/{len(checks)}',
                      'P1_human_review':'PENDING','science_scored':False,'test_opened':False}))
if __name__=='__main__':main()
